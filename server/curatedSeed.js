import { LIBRARY_CONFIG } from './config.js';

function smplSearchUrl(title, author = '') {
  return `${LIBRARY_CONFIG.catalogBaseUrl}/v2/search?query=${encodeURIComponent(`${title} ${author}`.trim())}&searchType=smart`;
}

